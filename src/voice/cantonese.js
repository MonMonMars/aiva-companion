/**
 * 按当前语言挑一句台词。
 * 粤语模式下优先用粤语台词；角色没写就用兜底池；都冇就退回普通话原文。
 *
 * @param {object} persona theme.js 里的人格对象
 * @param {string} category pet|poke|idle|gift|levelUp|lowMood
 * @param {string} lang 'zh-HK' | 'zh-CN' | 'en-US' | 'auto'
 */
export function personaLine(persona, category, lang) {
  const pickOne = (arr) => (arr && arr.length ? arr[Math.floor(Math.random() * arr.length)] : null);

  if (lang === YUE) {
    const mine = YUE_LINES[persona?.id] || {};
    const yue = pickOne(mine[category]) || pickOne(GENERIC_YUE[category]);
    if (yue) return yue;
  }
  return pickOne(persona?.voice?.[category]) || '';
}
