// ---------------------------------------------------------------------------
// 一、粤语音色挑选
// ---------------------------------------------------------------------------

/** 判断一个 SpeechSynthesisVoice 是不是粤语 */
export function isYueVoice(v) {
  const lang = String(v?.lang || '').toLowerCase().replace(/_/g, '-');
  const name = String(v?.name || '');
  if (lang.startsWith('yue')) return true;
  if (lang.startsWith('zh-hk')) return true;
  if (lang.startsWith('zh-hant-hk')) return true;
  if (/cantonese|粤语|粵語|廣東話|广东话|香港/i.test(name)) return true;
  return false;
}

/**
 * 从浏览器的音色列表里挑最合适的粤语声音。
 * 排序逻辑：zh-HK/yue 标签 > 本地音色（离线可用、不卡）> 女声（大部分角色设定是女的）。
 * @returns {SpeechSynthesisVoice|null} 一个粤语声音都没有时返回 null
 */
export function pickYueVoice(synth) {
  const voices = (synth && synth.getVoices && synth.getVoices()) || [];
  const yue = voices.filter(isYueVoice);
  if (!yue.length) return null;

  const score = (v) => {
    const lang = String(v.lang || '').toLowerCase().replace(/_/g, '-');
    const name = String(v.name || '');
    let s = 0;
    if (lang.startsWith('zh-hk') || lang.startsWith('yue')) s += 4;
    // 云端音色要联网才出声，移动网络下会明显延迟，能本地就本地
    if (v.localService) s += 2;
    // 大部分角色是女声设定，同名粤语音色里优先女声
    if (/female|女|hiugaai|hiumaan|gaai|sin-ji|meijia|佳|曼/i.test(name)) s += 1;
    return s;
  };
  return yue.slice().sort((a, b) => score(b) - score(a))[0] || null;
}

/**
 * 等音色列表就绪。
 *
 * getVoices() 在很多浏览器上是**异步**的：第一次调用返回空数组，要等
 * voiceschanged 事件。iOS 上更麻烦 —— 它有时压根不触发这个事件，
 * 所以除了监听事件还加了个轮询兜底。不等的话，第一次开口必定是普通话。
 *
 * @returns {Promise<SpeechSynthesisVoice[]>}
 */
export function ensureVoices(synth, timeout = 2500) {
  return new Promise((resolve) => {
    if (!synth || typeof synth.getVoices !== 'function') return resolve([]);

    const now = () => synth.getVoices() || [];
    let v = now();
    if (v.length) return resolve(v);

    let done = false;
    const finish = () => {
      if (done) return;
      done = true;
      try { synth.removeEventListener && synth.removeEventListener('voiceschanged', onChange); } catch (_) {}
      clearInterval(timer);
      resolve(now());
    };
    const onChange = () => { if (now().length) finish(); };

    try { synth.addEventListener && synth.addEventListener('voiceschanged', onChange); } catch (_) {}
    const t0 = Date.now();
    const timer = setInterval(() => {
      if (now().length || Date.now() - t0 > timeout) finish();
    }, 120);
    setTimeout(finish, timeout + 200);
  });
}

/**
 * iOS 解锁：Safari/内嵌 WebView 规定第一次 speak() 必须发生在用户手势里，
 * 否则静默失败（不报错、就是没声）。大模型回包是异步的，那时手势早就过了。
 *
 * 办法：在**第一次真实点击**时用一句空文本"预热"一次，之后异步说什么都行。
 * 所以这个要在点角色、点麦、戳一下的真正 onclick 里调用一次。
 */
export function unlockSpeech(synth) {
  if (!synth || synth.__yueUnlocked) return;
  try {
    const u = new SpeechSynthesisUtterance('');
    u.volume = 0;
    synth.speak(u);
    synth.__yueUnlocked = true;
  } catch (_) {}
}

