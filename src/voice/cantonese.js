// 粤语支持（语音 + 台词）
// ---------------------------------------------------------------------------
// 两件事分开处理，因为它们的失败方式完全不同：
//
//  1. **音色**：浏览器 SpeechSynthesis 里"粤语"不是一个开关，而是要自己在
//     getVoices() 那一长串里挑出来。只设 utterance.lang='zh-HK' 是不够的 ——
//     很多浏览器（尤其 iOS 上的内嵌 WebView）会挑一个普通话声音去念粤语稿，
//     念出来就是塑料粤语。必须显式指定 utterance.voice。
//
//  2. **台词**：戳一下、摸一下念的那些短句是写死在 theme.js 里的普通话。
//     就算换了粤语声音，念"干嘛啦，突然戳人！"依旧是普通话句子。
//     所以这里给每个角色单独写一套粤语台词。
//
// 台词用「简体 + 粤语字」的写法（佢/嘅/喺/咗/唔/啲/冇/点/边/而家）：
// 和 App 其余简体界面一致，广东、香港两边都读得顺，zh-HK 发音人也认得这些字。

