/**
 * 三级查找：人格自己的 > 通用池（按语言）> girlfriend 的。
 * 加新槽位时不用把 19 个人格全部铺一遍，也不会静默掉回 fallback。
 */
function scriptSlot(scripts, name, lang) {
  const own = scripts?.[name];
  if (own && own.length) return own;
  const pool = lang === 'zh-HK' ? SCRIPTS_YUE : SCRIPTS_GENERIC_CN;
  const alt = pool?.[name];
  if (alt && alt.length) return alt;
  return SCRIPTS.girlfriend?.[name] || null;
}

export function localReply(personaId, userText, lang) {
  const persona = getPersona(personaId);
  const scripts = (lang === 'zh-HK')
    ? SCRIPTS_YUE
    : (SCRIPTS[persona.id] || SCRIPTS.girlfriend);
  for (const rule of RULES) {
    if (rule.re.test(userText)) {
      const slot = scriptSlot(scripts, rule.slots[0], lang);
      if (slot) return pick(slot);
    }
  }
  return pick(scripts.fallback || SCRIPTS.girlfriend.fallback);
}

// ---------------------------------------------------------------------------
// 从用户的句子里抓「值得记住的事实」
// 轻量规则版，够用且不额外消耗 token
// ---------------------------------------------------------------------------
const MEMORY_PATTERNS = [
  { re: /(?:我叫|我是|叫我)\s*([^\s，。,.!！?？]{1,12})/, tpl: (m) => `用户自称 ${m[1]}` },
  { re: /我(?:叫|的名字是)\s*([^\s，。,.!！?？]{1,12})/, tpl: (m) => `用户名字是 ${m[1]}` },
  { re: /我(?:今年|是|)\s*(\d{1,3})\s*(?:岁|周岁)/, tpl: (m) => `用户 ${m[1]} 岁` },
  { re: /我(?:喜欢|爱|玩)\s*([^\s，。,.!！?？]{1,16})/, tpl: (m) => `用户喜欢${m[1]}` },
  { re: /我(?:讨厌|讨厌.|不想|不爱)\s*([^\s，。,.!！?？]{1,16})/, tpl: (m) => `用户讨厌${m[1]}` },
  { re: /我(?:住在|住在.|在)\s*([^\s，。,.!！?？]{1,10})(?:市|区|住)?$/, tpl: (m) => `用户可能在 ${m[1]}` },
  { re: /生日(?:是|在)?\s*(\d{1,2}月\d{1,2}日|\d{1,2}\/\d{1,2})/, tpl: (m) => `用户生日是 ${m[1]}` },
  { re: /我(?:是|是做|从事|在做)\s*([^\s，。,.!！?？]{1,14})(?:的|工作)?/, tpl: (m) => `用户职业相关：${m[1]}` },
];

export function extractMemory(text) {
  const t = String(text || '');
  if (t.length > 80) return null;
  for (const p of MEMORY_PATTERNS) {
    const m = t.match(p.re);
    if (m && m[1] && m[1].length >= 1) {
      return p.tpl(m);
    }
  }
  return null;
}
